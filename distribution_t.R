### Wendepunkt   x= +-sqrt(n/(n+2))                                        ###
w<- function(n){
result<- sqrt(n/(n+2))
return(result)
}

n<- 1:100
ex_w<- w(n)
plot(ex_w, type="l")

w2<- function(n){
result<- -sqrt(n/(n+2))
return(result)
}
n<- 1:100
ex_w2<- w2(n)
plot(ex_w2, type="l")