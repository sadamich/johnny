

A<- matrix(c(0,5,1,4), nrow=2,ncol=2)

P<- function(k1,k2){
A<- matrix(c(0,5,1,4), nrow=2,ncol=2)
I<- diag(2)
result<- (A - k2*I)/(k1 - k2)
return(result)
}
