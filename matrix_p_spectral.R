### The case 1

A<- matrix(c(0,5,1,4), nrow=2,ncol=2)

P<- function(k1,k2){
A<- matrix(c(0,5,1,4), nrow=2,ncol=2)
I<- diag(2)
result<- (A - k2*I)/(k1 - k2)
return(result)
}
P1<- P(5,-1)

          [,1]      [,2]
[1,] 0.1666667 0.1666667
[2,] 0.8333333 0.8333333

P2<- P(-1,5)

P1+ P2
